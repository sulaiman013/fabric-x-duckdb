"""End-to-end user acceptance test for the whole pipeline.

  python uat.py                  the full pass, roughly 15 minutes
  python uat.py --skip-source-scan   reuse the last recorded PostgreSQL counts
  python uat.py --no-capacity    local checks only, no capacity job

What it does, in the order the data flows:

  phase 0  the repository: secrets, ignore rules, every script parses, tests
  phase 1  ingestion: PostgreSQL settings, the slot, the replicator, and a
           real change pushed through the WAL and chased into OneLake
  phase 2  transformation: delegated to zz_uat_capacity, which can see the
           lakehouse (generated by build_uat_notebook.py, run here, merged back)
  phase 3  the semantic model: every measure evaluated against Direct Lake,
           reconciled to the verified gold layer, and timed
  phase 4  the application: the report's structure and its binding
  phase 5  the documentation: the numbers the README and BUILD_LOG claim,
           checked against what this run measured

Design rules, learned from the previous pass (BUILD_LOG section 36):

  * a check that cannot run is a FAIL or a SKIP, never a silent pass;
  * nothing is taken from an earlier section on trust, including this file's
    own constants, which is why the source counts are re-measured by default;
  * one failure never hides the next: every check is caught and recorded.

Writes UAT.md and UAT.json at the repository root, and exits non-zero if any
check failed.
"""

