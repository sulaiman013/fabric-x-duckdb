def phase2(state, run_capacity):
    print("\nPHASE 2  transformation, on the capacity")
    if not run_capacity:
        record("2.0", "the capacity half of the pass", "SKIP", "--no-capacity")
        return None

    sys.path.insert(0, HERE)
    import build_uat_notebook

    path = build_uat_notebook.build(pg_rows=state["pg_rows"],
                                    pg_distinct=state["pg_distinct"],
                                    probe_row=state["probe_row"],
                                    probe_token=state["probe_token"])
    out = subprocess.run(["fab", "import",
                          "fabric duckdb.Workspace/%s.Notebook" % UAT_NB,
                          "-i", path, "-f"],
                         capture_output=True, text=True, encoding="utf-8",
                         errors="replace", timeout=600)
    if "imported" not in (out.stdout or "").lower():
        record("2.0", "the capacity notebook imports", "FAIL",
               (out.stdout or out.stderr)[:200])
        return None

    items = api("workspaces/%s/items" % WS)["value"]
    nb_id = [i["id"] for i in items
             if i["displayName"] == UAT_NB and i["type"] == "Notebook"][0]
    start = subprocess.run(["fab", "job", "start",
                            "fabric duckdb.Workspace/%s.Notebook" % UAT_NB],
                           capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=300)
    # fab prints the id two ways and splits them across stdout and stderr, so
    # take the first UUID from either rather than matching one phrasing.
    m = re.search(r"[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}",
                  (start.stdout or "") + (start.stderr or ""))
    if not m:
        record("2.0", "the capacity notebook starts", "FAIL",
               (start.stdout or start.stderr)[:200])
        return None
    job = m.group(0)
    print("           capacity job %s" % job)

    status = None
    for _ in range(40):
        d = api("workspaces/%s/items/%s/jobs/instances/%s" % (WS, nb_id, job))
        status = d.get("status")
        if status in ("Completed", "Failed", "Cancelled", "Deduped"):
            break
        time.sleep(30)
    if status != "Completed":
        record("2.0", "the capacity notebook completes", "FAIL",
               "job %s ended %s: %s" % (job, status, str(d.get("failureReason"))[:200]))
        return None

    dest = os.path.join(ROOT, "uat_capacity.json")
    subprocess.run(["fab", "cp",
                    "fabric duckdb.Workspace/fincrime.Lakehouse/Files/uat_capacity.json",
                    dest.replace("\\", "/"), "-f"],
                   capture_output=True, text=True, timeout=300)
    if not os.path.isfile(dest):
        record("2.0", "the capacity results come back", "FAIL",
               "uat_capacity.json was not produced")
        return None
    cap = json.load(io.open(dest, encoding="utf-8"))
    os.remove(dest)
    for c in cap["checks"]:
        record(c["id"], c["name"], "PASS" if c["ok"] else "FAIL", c["detail"])
    return cap


# ------------------------------------------------------------------ phase 3
def phase3(cap):
    print("\nPHASE 3  the Direct Lake semantic model")

    def measure_names():
        names = []
        base = os.path.join(ROOT, "semantic-model", "definition", "tables")
        for f in sorted(os.listdir(base)):
            for line in io.open(os.path.join(base, f), encoding="utf-8"):
                m = re.match(r"\s*measure '([^']+)'", line)
                if m:
                    names.append(m.group(1))
        return names

    def c_direct_lake():
        base = os.path.join(ROOT, "semantic-model", "definition", "tables")
        modes = set()
        for f in os.listdir(base):
            for line in io.open(os.path.join(base, f), encoding="utf-8"):
                m = re.match(r"\s*mode:\s*(\w+)", line)
                if m:
                    modes.add(m.group(1))
        return modes == {"directLake"}, "partition modes authored: %s" % sorted(modes)

    def c_measures_resolve():
        names = measure_names()
        bad = []
        for n in names:
            try:
                rows = dax('EVALUATE ROW("v", [%s])' % n)
                if not rows:
                    bad.append("%s: no rows" % n)
            except Exception as e:
                bad.append("%s: %s" % (n, str(e)[:80]))
        return not bad, "all %d measures resolve against Direct Lake" % len(names) \
            if not bad else str(bad[:4])

    def c_reconcile():
        """The model must agree with the layer verify.json signed off, or the
        report is showing something the pipeline never produced."""
        if not cap:
            return None, "needs the capacity half"
        v = cap["notes"]["verify"]["tables"]
        rows = dax('EVALUATE ROW("txns", [Transactions], "firings", [Rule Firings], '
                   '"amt", [Total Amount], "alerts", [Alerts Raised])')[0]
        txns, firings = rows["[txns]"], rows["[firings]"]
        ok = (txns == v["fact_transaction"]["rows"]
              and firings == v["fact_alert"]["rows"])
        return ok, ("Transactions %s vs gold %s; Rule Firings %s vs gold %s; "
                    "Total Amount %s; Alerts %s" % (
                        format(txns, ","), format(v["fact_transaction"]["rows"], ","),
                        format(firings, ","), format(v["fact_alert"]["rows"], ","),
                        rows["[amt]"], format(rows["[alerts]"], ",")))

    def c_latency():
        queries = {
            "headline KPIs": 'EVALUATE ROW("t", [Transactions], "a", [Alerts Raised])',
            "overview cube": ('EVALUATE SUMMARIZECOLUMNS(dim_date[yr], dim_date[mth], '
                              'dim_channel[channel], fact_transaction[risk_band], '
                              'fact_transaction[txn_type], "t", [Transactions])'),
            "rules by band": ('EVALUATE SUMMARIZECOLUMNS(fact_transaction[rules_fired], '
                              'fact_transaction[risk_band], "t", [Transactions])'),
        }
        out = {}
        for name, q in queries.items():
            times = []
            for _ in range(3):
                t0 = time.perf_counter()
                rows = dax(q)
                times.append(round(time.perf_counter() - t0, 2))
            out[name] = {"rows": len(rows), "seconds": times}
        warm = max(t["seconds"][-1] for t in out.values())
        # Each timing includes roughly two seconds of `fab` process startup,
        # because every query is a separate CLI invocation. The figure a report
        # user actually sees is measured inside the capacity by 00_README and
        # is about a second; this check is a ceiling, not a benchmark.
        return warm < 20, "%s (each includes ~2s of CLI startup)" % "; ".join(
            "%s %s rows %s" % (k, v["rows"], v["seconds"]) for k, v in out.items())

    check("3.1", "the model is authored as Direct Lake", c_direct_lake)
    check("3.2", "every measure resolves", c_measures_resolve)
    check("3.3", "the model reconciles to the verified gold layer", c_reconcile)
    check("3.4", "report queries answer in seconds, not minutes", c_latency)


