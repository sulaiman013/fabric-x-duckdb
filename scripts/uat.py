def phase4():
    print("\nPHASE 4  the report")
    rep = os.path.join(ROOT, "report", "FinCrime.Report", "definition")

    def c_pages():
        pages = json.load(io.open(os.path.join(rep, "pages", "pages.json"),
                                  encoding="utf-8"))
        order = pages.get("pageOrder", [])
        on_disk = sorted(d for d in os.listdir(os.path.join(rep, "pages"))
                         if os.path.isdir(os.path.join(rep, "pages", d)))
        ok = (len(order) == 4 and sorted(order) == on_disk
              and order[-1].lower() == "guide")
        return ok, "pageOrder %s, folders %s" % (order, on_disk)

    def c_visuals():
        """Every page carries exactly the content visual and the navigator.
        PBIR renders every folder it finds, so an orphan is a visible defect."""
        bad = []
        for d in sorted(os.listdir(os.path.join(rep, "pages"))):
            vdir = os.path.join(rep, "pages", d, "visuals")
            if not os.path.isdir(vdir):
                continue
            vis = sorted(os.listdir(vdir))
            if len(vis) != 2:
                bad.append("%s has %d visuals: %s" % (d, len(vis), vis))
                continue
            kinds = set()
            for v in vis:
                j = json.load(io.open(os.path.join(vdir, v, "visual.json"),
                                      encoding="utf-8"))
                kinds.add(j.get("visual", {}).get("visualType", "?"))
            if "pageNavigator" not in kinds:
                bad.append("%s has no page navigator: %s" % (d, kinds))
        return not bad, "4 pages, each with a content visual and a navigator" \
            if not bad else str(bad)

    def c_extensions():
        ext = json.load(io.open(os.path.join(rep, "reportExtensions.json"),
                                encoding="utf-8"))
        ents = ext.get("entities", [])
        names = [m["name"] for e in ents for m in e.get("measures", [])]
        entity_ok = all(e["name"] == "fact_transaction" for e in ents)
        return (entity_ok and len(names) == 4,
                "%d report measures on %s" % (len(names),
                                              [e["name"] for e in ents]))

    def c_binding():
        d = json.load(io.open(os.path.join(rep, "..", "definition.pbir"),
                              encoding="utf-8"))
        conn = json.dumps(d.get("datasetReference", {}))
        return ("semanticModelId" in conn,
                "byConnection carries a semanticModelId" if "semanticModelId" in conn
                else conn[:200])

    def c_published():
        items = api("workspaces/%s/items" % WS)["value"]
        r = [i for i in items if i["id"] == REPORT_ID]
        return bool(r), "FinCrime is published in the workspace" if r \
            else "report %s not found" % REPORT_ID

    check("4.1", "the report has four pages, the guide last", c_pages)
    check("4.2", "no orphaned visuals on any page", c_visuals)
    check("4.3", "the report measures bind to a real entity", c_extensions)
    check("4.4", "the report binds to the semantic model by connection", c_binding)
    check("4.5", "the report is published", c_published)


# ------------------------------------------------------------------ phase 5
def phase5(state, cap):
    print("\nPHASE 5  the documentation")
    readme = io.open(os.path.join(ROOT, "README.md"), encoding="utf-8").read()
    buildlog = io.open(os.path.join(ROOT, "BUILD_LOG.md"), encoding="utf-8").read()

    def c_no_dashes():
        bad = []
        for name, text in (("README.md", readme), ("BUILD_LOG.md", buildlog)):
            for ch, label in (("\u2014", "em dash"), ("\u2013", "en dash")):
                if ch in text:
                    bad.append("%s contains a %s" % (name, label))
        return not bad, "no em or en dashes in the docs" if not bad else str(bad)

    def c_logged_instruction():
        """The most dangerous defect an earlier pass found was a README that
        told the reader to load UNLOGGED, which silently breaks CDC. The
        warning has to survive every rewrite of this document."""
        ok = "UNLOGGED" in readme and "LOGGED" in readme
        return ok, ("the README still warns that logical replication never "
                    "captures an UNLOGGED table"
                    if ok else "the UNLOGGED warning has been lost")

    def c_numbers():
        if not cap:
            return None, "needs the capacity half"
        b = cap["notes"]["build"]
        claims = {
            "gold rows": format(b["counts"]["fact_transaction"], ","),
            "duplicates removed": format(b["recon"]["removed"], ","),
        }
        bad = [k for k, v in claims.items() if v not in readme]
        return not bad, ("the README quotes this run's %s" % ", ".join(claims)
                         if not bad else "the README does not quote: %s" % bad)

    def c_readme_is_the_notebook():
        """README.md is the prose of the 00_README notebook, which is the thing
        that runs on the capacity and measures itself. Two copies of the same
        document drift, so this asserts they have not."""
        nb = json.load(io.open(os.path.join(
            ROOT, "notebooks", "00_README.Notebook", "notebook-content.ipynb"),
            encoding="utf-8"))
        md = [("".join(c["source"])).rstrip("\n") for c in nb["cells"]
              if c["cell_type"] == "markdown" and "".join(c["source"]).strip()]
        want = "\n\n".join(md) + "\n"
        if want == readme:
            return True, "README.md is exactly the notebook's %d markdown cells" % len(md)
        return False, ("README.md has drifted from 00_README.Notebook "
                       "(%d vs %d chars); regenerate it from the notebook"
                       % (len(readme), len(want)))

    check("5.1", "no em or en dashes in the documentation", c_no_dashes)
    check("5.2", "the README still warns about UNLOGGED", c_logged_instruction)
    check("5.3", "the README quotes the numbers this run measured", c_numbers)
    check("5.4", "the README is the workspace notebook, not a second copy",
          c_readme_is_the_notebook)


# ------------------------------------------------------------------- report
def write_report(state, cap, started):
    passed = sum(1 for c in CHECKS if c["state"] == "PASS")
    failed = [c for c in CHECKS if c["state"] == "FAIL"]
    skipped = [c for c in CHECKS if c["state"] == "SKIP"]
    stamp = time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime(started))

    lines = ["# End-to-end UAT", "",
             "Generated by `scripts/uat.py`. Every line is a check that ran "
             "against the live pipeline, not a claim copied from a document.",
             "",
             "| Run | Value |", "| --- | --- |",
             "| Started | %s |" % stamp,
             "| Duration | %.1f minutes |" % ((time.time() - started) / 60),
             "| Result | **%d passed, %d failed, %d skipped** |"
             % (passed, len(failed), len(skipped)), ""]

    if failed:
        lines += ["## Failures", ""]
        for c in failed:
            lines.append("* **%s %s**: %s" % (c["id"], c["name"], c["detail"]))
        lines.append("")

    groups = [("0", "Repository"), ("1", "Phase 1: ingestion"),
              ("2", "Phase 2: transformation"), ("3", "Phase 3: semantic model"),
              ("4", "Phase 4: application"), ("5", "Documentation")]
    for prefix, title in groups:
        rows = [c for c in CHECKS
                if c["id"].lstrip("P").startswith(prefix)]
        if not rows:
            continue
        lines += ["## %s" % title, "", "| Check | Result | Evidence |",
                  "| --- | --- | --- |"]
        for c in rows:
            detail = c["detail"].replace("|", "\\|").replace("\n", " ")
            lines.append("| %s %s | %s | %s |" % (c["id"], c["name"],
                                                  c["state"], detail))
        lines.append("")

    io.open(os.path.join(ROOT, "UAT.md"), "w", encoding="utf-8",
            newline="\n").write("\n".join(lines) + "\n")
    io.open(os.path.join(ROOT, "UAT.json"), "w", encoding="utf-8",
            newline="\n").write(json.dumps(
                {"ran_at_utc": stamp, "passed": passed, "failed": len(failed),
                 "skipped": len(skipped), "checks": CHECKS,
                 "capacity": (cap or {}).get("notes", {})},
                indent=1, default=str) + "\n")
    return passed, failed, skipped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-source-scan", action="store_true",
                    help="reuse the recorded PostgreSQL counts instead of a 4 minute scan")
    ap.add_argument("--no-capacity", action="store_true",
                    help="local checks only")
    args = ap.parse_args()

    started = time.time()
    print("END-TO-END UAT  %s" % time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime()))
    phase0()
    state = phase1(args.skip_source_scan)
    cap = phase2(state, not args.no_capacity)
    phase3(cap)
    phase4()
    phase5(state, cap)

    passed, failed, skipped = write_report(state, cap, started)
    print("\n%s" % ("-" * 66))
    print("VERDICT: %d passed, %d failed, %d skipped, in %.1f minutes"
          % (passed, len(failed), len(skipped), (time.time() - started) / 60))
    for c in failed:
        print("  FAILED %s %s: %s" % (c["id"], c["name"], c["detail"][:160]))
    print("report written to UAT.md")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
